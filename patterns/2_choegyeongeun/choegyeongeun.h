static void dampCabinet(float& value, float& velocity, float target, float response,
                        float dt, float lo, float hi) {
  const float offset = value - target;
  const float j = velocity + response * offset;
  const float decay = expf(-response * dt);
  float next = target + (offset + j * dt) * decay;
  float vel = (velocity - response * j * dt) * decay;
  if (next < lo || next > hi) {
    next = clampf(next, lo, hi);
    vel = 0.0f;
  }
  if (fabsf(next - target) < 1e-4f && fabsf(vel) < 1e-3f) {
    next = target;
    vel = 0.0f;
  }
  value = next;
  velocity = vel;
}

// f.x, f.y of scene s's flowers from their state (the JS's position lines)
static void placeScene(int s) {
  const int first = SCENE_START[s];
  const int count = SCENE_START[s + 1] - first;
  const float xMin = 13.0f, yMin = 20.0f, spanX = 37.0f, spanY = 87.0f;
  for (int i = 0; i < count; i++) {
    const int g = first + i;
    const FlowerC& f = FLOWERS[g];
    const float margin = f.baseR + 6.0f;
    float x, y;
    if (s == 0) {
      x = xMin + fProgX[g] * spanX + sinf(fDrift[g] + fPhase[g]) * f.driftAmp;
      y = (yMin - margin) + fProgY[g] * (spanY + margin * 2.0f);
    } else if (s == 1) {
      x = (xMin - margin) + fProgX[g] * (spanX + margin * 2.0f);
      y = yMin + fProgY[g] * spanY + sinf(fDrift[g] + fPhaseY[g]) * f.driftAmp;
    } else if (s == 2) {
      const float k = 0.7f + f.depth * 0.3f;
      x = 31.5f + sinf(fPhase[g]) * (10.5f * k);
      y = 63.5f + cosf(fPhaseY[g]) * (34.0f * k);
    } else {
      const float sway = f.loose ? 3.2f : 1.8f;
      x = (xMin - margin) + fProgX[g] * (spanX + margin * 2.0f) + sinf(1.2f * fDrift[g] + fPhase[g]) * sway;
      y = (yMin - margin) + fProgY[g] * (spanY + margin * 2.0f);
    }
    curX[i] = x;
    curY[i] = y;
  }
  posScene = s;
}

