// ── Lines in ────────────────────────────────────────────────────────────
// {"c":"usb"}: the USB controller's registers as they are, as one line. For
// the day a pipe to the computer has stopped: the hub can be asked what it
// sees without being rebuilt for it (seen 2026-11-21: MIDI to the computer
// stood still from the first message after a start until the hub restarted,
// and nothing here could say why).
bool usbLine(const char* text, size_t len) {
  if (len < 11 || memcmp(text, "{\"c\":\"usb\"", 10) != 0) return false;
  static char line[HUB_LINE_MAX];
  const size_t head = (size_t)snprintf(line, sizeof(line), "{\"t\":\"usb\",\"d\":");
  const size_t n = usb_s3::dump(line + head, sizeof(line) - head - 2);
  if (!n || head + n + 2 >= sizeof(line) || line[head + n - 1] != '}') return true;   // it did not fit: say nothing
  line[head + n] = '}';
  consoleLine(nullptr, line, head + n + 1);
  return true;
}

void handleLine(Port* port, const char* text, size_t len) {
  if (!len || text[0] != '{') return;     // typing in a serial monitor, or noise
  if (port) {
    if (!port->listening) {
      port->listening = true;
      // Whoever just arrived missed everything so far.
      conductor.sendAll();
    }
    port->heardMs = millis();
  }
  if (relayLine(text, len)) return;
  if (usbLine(text, len)) return;
#ifndef HUB_STA_SSID
  if (setup_::line(text, len, port)) return;
#endif
  const pfe::ConsoleResult res = console->handle(text, len);
  if (res.rebootHub && !restartAsked) {
    restartAsked = true;
    restartAtMs = millis() + 400;
    hubLog("restarting: asked from the console");
  }
}

void feed(Port& port, int c) {
  if (c == '\n' || c == '\r') {
    if (port.len && !port.overflow) handleLine(&port, port.line, port.len);
    port.len = 0;
    port.overflow = false;
    return;
  }
  if (port.len + 1 < sizeof(port.line)) port.line[port.len++] = (char)c;
  else port.overflow = true;
}

void readPorts() {
  for (int budget = 4096; budget > 0 && usbConsole.available(); budget--) feed(usbPort, usbConsole.read());
  for (int budget = 512; budget > 0 && Serial.available(); budget--) feed(uartPort, Serial.read());

  static char line[IN_LINE_MAX];
  for (int budget = 16; budget > 0; budget--) {
    const size_t n = xMessageBufferReceive(fromSocket, line, sizeof(line), 0);
    if (!n) break;
    size_t start = 0;
    for (size_t i = 0; i <= n; i++) {
      if (i < n && line[i] != '\n') continue;
      handleLine(nullptr, line + start, i - start);
      start = i + 1;
    }
  }
  if (socketJoined) {
    socketJoined = false;
    conductor.sendAll();
  }

  const uint32_t now = millis();
  for (Port* p : {&usbPort, &uartPort}) {
    if (p->listening && now - p->heardMs > HUB_CONSOLE_QUIET_MS) p->listening = false;
  }
  // A busy panel's line ten times a second is fine over USB and Wi-Fi, and
  // far too much for 115200 baud when the UART is the only console.
  const bool fast = usbPort.listening || socket.count() > 0;
  conductor.setConsoleRate(fast || !uartPort.listening ? 100 : 500);
}

void onSocket(AsyncWebSocket*, AsyncWebSocketClient*, AwsEventType type, void* arg, uint8_t* data, size_t len) {
  if (type == WS_EVT_CONNECT) {
    socketJoined = true;
    return;
  }
  if (type != WS_EVT_DATA) return;
  const AwsFrameInfo* info = (const AwsFrameInfo*)arg;
  // Whole text frames only; a console line is far shorter than one frame.
  if (!info->final || info->index != 0 || info->len != len || info->opcode != WS_TEXT) return;
  xMessageBufferSend(fromSocket, data, len, 0);
}

