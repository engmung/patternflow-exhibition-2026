// One writer per serial port, so that only this task waits for a laptop.
//
// The core's USBCDC::write() does more than wait: with the port open and
// its buffer full it spins until there is room (cores/esp32/USBCDC.cpp), and
// a task that spins keeps the idle task from running until the watchdog
// restarts the board. A console whose tab has frozen is exactly that. So
// this never hands write() more than the port says it can take, and when
// nothing has moved for half a second it lets the line go and stays quiet
// for a while. Lines are state; the next ones repair it.
//
// The buffer is 64 bytes (the core's CONFIG_TINYUSB_CDC_TX_BUFSIZE), one USB
// packet, so "no room" is the ordinary state between two packets of a line
// and lasts about a millisecond. The clocks here run on flags, not on "zero
// means not running": `millis() | 1` for a never-zero start put the start a
// millisecond ahead of now half the time, the unsigned subtraction wrapped,
// and the line was given up - with two seconds of silence after it - the
// moment the buffer first filled. The USB console delivered a few hundred
// bytes a second and looked broken (found 2026-11-14 with /api/status: the
// buffer empty and nothing in flight, and "stalls" counting up).
TaskHandle_t usbWriterTask = nullptr;

// Whether a program has the USB serial port open: DTR, as TinyUSB holds it.
// Not the core's own `if (usbConsole)`: that flag passes through the core's
// auto-reset detector (USBCDC::_onLineState), which reads the order DTR and
// RTS come up in, and a port opened RTS-first leaves it false for good - the
// console was open and got nothing (2026-11-14, every second time it opened).
// And not before the transmit FIFOs are where they belong (usb_s3.cpp).
inline bool usbOpen() { return usb_s3::ready() && tud_cdc_n_connected(0); }

void usbWriter(void*) {
  static char line[HUB_LINE_MAX + 2];
  bool quiet = false, cutLine = false;
  uint32_t quietSinceMs = 0;
  for (;;) {
    size_t n = xMessageBufferReceive(toUsb, line, HUB_LINE_MAX, portMAX_DELAY);
    if (!n || !usbOpen()) {                             // nobody has the port open
      cutLine = false;
      continue;
    }
    if (quiet && millis() - quietSinceMs < HUB_USB_QUIET_MS) continue;
    quiet = false;
    size_t off = 0;
    if (cutLine) {              // the line given up on ended nowhere: end it, so this one starts on its own
      memmove(line + 1, line, n);
      line[0] = '\n';
      n++;
      cutLine = false;
    }
    line[n++] = '\n';
    bool stuck = false;
    uint32_t stuckSinceMs = 0;
    while (off < n && usbOpen()) {
      const int space = usbConsole.availableForWrite();
      if (space <= 0) {
        if (!stuck) {
          stuck = true;
          stuckSinceMs = millis();
        }
        if (millis() - stuckSinceMs > HUB_USB_STALL_MS) {
          quiet = true;
          quietSinceMs = millis();
          cutLine = off > 0;
          usbStalls++;
          break;
        }
        ulTaskNotifyTake(pdTRUE, 1);    // until the packet has gone (onUsbSent), a tick at most
        continue;
      }
      stuck = false;
      const size_t chunk = (size_t)space < n - off ? (size_t)space : n - off;
      const size_t sent = usbConsole.write((const uint8_t*)line + off, chunk);
      if (!sent) break;
      off += sent;
      usbBytes += sent;
    }
  }
}

// A packet reached the computer: there is room again.
void onUsbSent(void*, esp_event_base_t, int32_t, void*) {
  if (usbWriterTask) xTaskNotifyGive(usbWriterTask);
}

// The computer sent more than the port's buffer holds before loop() read it:
// the core drops what does not fit, and a line arrives with a hole in it.
// Counted, and said in the log, because it looks like anything but this from
// outside (2026-11-21: uploads to four panels at once failed "not the bytes
// that were promised", one request in twenty, with a buffer of 4096).
void onUsbRxOverflow(void*, esp_event_base_t, int32_t, void* data) {
  const arduino_usb_cdc_event_data_t* e = (const arduino_usb_cdc_event_data_t*)data;
  usbRxLost += e ? e->rx_overflow.dropped_bytes : 1;
}

// The one way into the bootloader over USB: the port set to 1200 baud, the
// Arduino convention (PlatformIO's use_1200bps_touch, platformio.ini). The
// core's own detector is switched off in setup(): besides this it restarts
// the board on esptool's DTR/RTS sequence, which a console that opens the
// port RTS-first and closes it RTS-first also produces - and a hub that
// drops into its bootloader when a browser tab closes stays there.
void onUsbLineCoding(void*, esp_event_base_t, int32_t, void* data) {
  const arduino_usb_cdc_event_data_t* e = (const arduino_usb_cdc_event_data_t*)data;
  if (e && e->line_coding.bit_rate == 1200) usb_persist_restart(RESTART_BOOTLOADER);
}

void uartWriter(void*) {
  static char line[HUB_LINE_MAX + 2];
  for (;;) {
    size_t n = xMessageBufferReceive(toUart, line, HUB_LINE_MAX, portMAX_DELAY);
    if (!n) continue;
    line[n++] = '\n';
    Serial.write((const uint8_t*)line, n);
  }
}

// ── The console's requests to a panel's web server (pfe_relay.h) ─────────
// The console is on a cable to the hub, the panels' web servers are on the
// hub's Wi-Fi: a pattern file for a panel comes in as lines and leaves here
// as HTTP, and the panel's answer goes back as lines.
struct PanelSocket : pfe::RelaySocket {
  WiFiClient client;
  bool connect(uint32_t ip, uint16_t port, uint32_t timeoutMs) override {
    client.stop();
    const IPAddress to((uint8_t)(ip >> 24), (uint8_t)(ip >> 16), (uint8_t)(ip >> 8), (uint8_t)ip);
    if (!client.connect(to, port, (int32_t)timeoutMs)) return false;
    client.setNoDelay(true);
    return true;
  }
  size_t write(const uint8_t* data, size_t len) override { return client.write(data, len); }
  int available() override { return client.available(); }
  int read(uint8_t* out, size_t cap) override { return client.read(out, cap); }
  bool connected() override { return client.connected(); }
  void stop() override { client.stop(); }
};
PanelSocket relaySockets[RELAYS];
pfe::Relay relays[RELAYS];
uint32_t relayRequests = 0;

// How much a console that is listening can still be sent: the least of them.
size_t consoleRoom(void*) {
  size_t room = OUT_BUFFER;
  if (usbPort.listening) room = min(room, xMessageBufferSpacesAvailable(toUsb));
  if (uartPort.listening) room = min(room, xMessageBufferSpacesAvailable(toUart));
  if (socket.count() && !socket.availableForWriteAll()) room = 0;
  return room;
}

// {"c":"http"} and {"c":"hb"}; false for any other line.
bool relayLine(const char* text, size_t len) {
  if (len < 12 || memcmp(text, "{\"c\":\"h", 7) != 0) return false;
  pfe::JObject o;
  if (!o.parse(text, len)) return false;
  int id = 0;
  o.integer("id", &id);
  if (o.is("c", "hb")) {
    for (pfe::Relay& r : relays)
      if (r.busy() && r.id() == id) r.body(o, millis());
    return true;
  }
  if (!o.is("c", "http")) return false;
  const int i = console->panelOf(o, "to");
  uint32_t ip = i >= 0 && conductor.panel(i).online ? conductor.panel(i).ep.ip : 0;
#ifndef HUB_STA_SSID
  // Or a device on the hub's own hotspot by its address: a panel that has
  // just been brought in and does not run the ensemble's firmware yet, so
  // the hub knows no panel by that name. Setup puts the firmware on it this
  // way. Nothing outside the hotspot's own network.
  if (i < 0) {
    const pfe::JVal* a = o.get("ip");
    unsigned b[4] = {0, 0, 0, 0};
    char at[20] = "";
    if (a && a->type == 's' && a->n < sizeof(at)) {
      memcpy(at, a->p, a->n);
      const uint8_t home[4] = {HUB_AP_IP};
      if (sscanf(at, "%u.%u.%u.%u", &b[0], &b[1], &b[2], &b[3]) == 4 && b[0] == home[0] && b[1] == home[1] &&
          b[2] == home[2] && b[3] >= 2 && b[3] <= 254)
        ip = ((uint32_t)b[0] << 24) | ((uint32_t)b[1] << 16) | ((uint32_t)b[2] << 8) | b[3];
    }
  }
#endif
  pfe::Relay* use = &relays[0];        // with all of them busy the first says so
  for (pfe::Relay& r : relays)
    if (!r.busy()) { use = &r; break; }
  relayRequests++;
  use->request(o, ip, millis());
  return true;
}

// ── Setup: bringing a new panel in ──────────────────────────────────────
// A panel that knows no Wi-Fi starts a hotspot of its own, "patternflow-"
// and the last four digits of its address. To join the ensemble it has to
// be told the hub's network, and somebody has to be on its hotspot to tell
// it. That used to be a laptop (tools/panels.py). Here the hub goes itself:
//
//   {"c":"setup","op":"scan"}                 look for such hotspots
//   {"c":"setup","op":"join","ssid":"patternflow-1a2b","pass":"..."}
//                                             go onto that hotspot, give the
//                                             panel the hub's network, make
//                                             it the one the panel starts
//                                             from, send it there, come back
//   {"c":"setup","op":"stations"}             who is on the hub's hotspot
//   {"c":"setup","op":"net"}                  the hub's own network, name and
//                                             password - for a console that
//                                             sends a panel there itself (one
//                                             on the room's Wi-Fi, which the
//                                             hub cannot see). Answered on a
//                                             serial port only, and only to
//                                             the port that asked: whoever is
//                                             on the hub's Wi-Fi knows it, and
//                                             nobody else is to be told.
//
// and answers in {"t":"setup",...} lines. The hub has one radio: while it is
// on a panel's hotspot its own hotspot is on that hotspot's channel, and the
// panels of the ensemble lose it for those seconds and find it again. Setup
// is for before a show. Hotspot mode only (a hub on a router would have to
// leave the router).
