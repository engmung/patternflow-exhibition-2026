void loadSetup() {
  static uint8_t blob[pfe::SAVE_MAX];
  if (!prefs.begin("pfe", true)) return;
  const size_t n = prefs.getBytes("setup", blob, sizeof(blob));
  prefs.end();
  if (!n) { Serial.println("[hub] no saved setup: starting empty"); return; }
  const bool ok = conductor.load(blob, n);
  Serial.printf("[hub] saved setup: %u bytes, %s, %d panels known\n", (unsigned)n,
                ok ? "loaded" : "NOT understood (ignored)", conductor.panelCount());
}

// The graph's program: its own entry beside the setup, written a moment
// after it changes (a console that edits a graph sends one at every change).
void loadGraph() {
  static uint8_t blob[pfe::GRAPH_MAX_BYTES];
  if (!prefs.begin("pfe", true)) return;
  const size_t n = prefs.getBytes("graph", blob, sizeof(blob));
  const bool on = prefs.getBool("graphon", false);
  prefs.end();
  const char* problem = n ? graph.load(blob, n, millis()) : nullptr;
  graph.setEnabled(on, millis());
  graph.takeChanged();                   // it is what the flash holds already
  if (n) Serial.printf("[hub] saved graph: %u bytes, %s, switched %s\n", (unsigned)n, problem ? problem : "understood", on ? "on" : "off");
}

void saveGraphIfDue() {
  static bool due = false;
  static uint32_t changedMs = 0;
  if (graph.takeChanged()) { due = true; changedMs = millis(); }
  if (!due || millis() - changedMs < HUB_SAVE_AFTER_MS) return;
  due = false;
  if (!prefs.begin("pfe", false)) { hubLog("graph NOT saved (flash)"); return; }
  if (graph.active()) {
    if (prefs.putBytes("graph", graph.bytes(), graph.size()) != graph.size()) hubLog("graph NOT saved");
  } else {
    prefs.remove("graph");
  }
  prefs.putBool("graphon", graph.enabled());
  prefs.end();
}

void saveSetupIfDue() {
  if (!conductor.persistDirty() || millis() - conductor.persistChangedMs() < HUB_SAVE_AFTER_MS) return;
  static uint8_t blob[pfe::SAVE_MAX];
  const size_t n = conductor.save(blob, sizeof(blob));
  conductor.clearPersistDirty();
  if (!n || !prefs.begin("pfe", false)) { hubLog("setup NOT saved (flash)"); return; }
  const size_t written = prefs.putBytes("setup", blob, n);
  prefs.end();
  if (written != n) hubLog("setup NOT saved: %u of %u bytes written", (unsigned)written, (unsigned)n);
}

// ── USB-MIDI ──────────────────────────────────────────────────────────
// A class-compliant MIDI interface beside the console's serial port, on the
// USB jack: a DAW sees a MIDI device named HUB_USB_NAME. What goes over it is
// ../../core/pfe_midi.h. The Arduino core 2.0.x carries TinyUSB's MIDI class
// (CONFIG_TINYUSB_MIDI_ENABLED) without a wrapper for it; this is that
// wrapper, registered the way the core's own classes register themselves.
bool midiWasMounted = false;

uint16_t loadMidiDescriptor(uint8_t* dst, uint8_t* itf) {
  const uint8_t str = tinyusb_add_string_descriptor(HUB_USB_NAME);
  const uint8_t ep = tinyusb_get_free_duplex_endpoint();
  const uint8_t desc[TUD_MIDI_DESC_LEN] = {TUD_MIDI_DESCRIPTOR(*itf, str, ep, (uint8_t)(0x80 | ep), 64)};
  *itf += 2;   // audio control + MIDI streaming
  midiEpIn = (uint8_t)(0x80 | ep);
  memcpy(dst, desc, sizeof(desc));
  return sizeof(desc);
}

// One message out, as a USB-MIDI packet: cable 0, the code index is the
// status byte's high nibble for every channel message. False: the port has
// no room (its 64 bytes hold sixteen messages, and nobody is taking them) or
// is not there; pfe::Midi keeps the value and offers it again.
bool midiOut(void*, const uint8_t* m, size_t n) {
  if (!HUB_USB_MIDI || !usb_s3::ready() || !tud_midi_mounted()) return false;
  const uint8_t packet[4] = {(uint8_t)(m[0] >> 4), m[0], n > 1 ? m[1] : (uint8_t)0, n > 2 ? m[2] : (uint8_t)0};
  if (!tud_midi_packet_write(packet)) {
    midiRefused++;
    return false;
  }
  midiWritten++;
  return true;
}

void readMidi() {
  if (!HUB_USB_MIDI) return;
  const bool mounted = tud_midi_mounted();
  if (mounted != midiWasMounted) {
    midiWasMounted = mounted;
    hubLog(mounted ? "MIDI: the computer has the USB-MIDI port" : "MIDI: the USB-MIDI port is gone");
  }
  if (!mounted) return;
  uint8_t packet[4];
  for (int budget = 32; budget > 0 && tud_midi_packet_read(packet); budget--) {
    const uint8_t cin = packet[0] & 0x0F;
    if (cin < 0x8 || cin > 0xE) continue;            // channel messages only
    const size_t len = (cin == 0xC || cin == 0xD) ? 2 : 3;
    // The graph's switch on: MIDI goes through the wires only, and none of it the plain way.
    if (graph.onMidi(packet + 1, len, millis())) continue;
    midi.onMessage(packet + 1, len);
  }
}

