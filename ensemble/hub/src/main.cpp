// ── Lines out ───────────────────────────────────────────────────────────
void consoleLine(void*, const char* text, size_t len) {
  if (len >= HUB_LINE_MAX) return;
  if (usbPort.listening && xMessageBufferSend(toUsb, text, len, 0) == 0) linesDropped++;
  if (uartPort.listening && xMessageBufferSend(toUart, text, len, 0) == 0) linesDropped++;
  if (socket.count() && socket.availableForWriteAll()) socket.textAll(text, len);
}

void sendPacket(void*, const pfe::Endpoint& to, const uint8_t* data, size_t len) {
  if (!udpOpen) return;
  const IPAddress ip((uint8_t)(to.ip >> 24), (uint8_t)(to.ip >> 16), (uint8_t)(to.ip >> 8), (uint8_t)to.ip);
  if (!udp.beginPacket(ip, to.port)) return;
  udp.write(data, len);
  udp.endPacket();
}

