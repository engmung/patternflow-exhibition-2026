void wifiTick() {
  static bool started = false;
#ifdef HUB_STA_SSID
  if (!started) {
    started = true;
    WiFi.mode(WIFI_STA);
    WiFi.setHostname(HUB_HOSTNAME);
    WiFi.setSleep(false);              // modem sleep adds up to a beacon of latency to every STATE
    WiFi.setAutoReconnect(true);
    WiFi.begin(HUB_STA_SSID, HUB_STA_PASS);
    hubLog("router mode: joining \"%s\"", HUB_STA_SSID);
  }
  const bool up = WiFi.status() == WL_CONNECTED;
  if (up && !wifiUp) {
    hubLog("on \"%s\" as %s, http://%s.local/", HUB_STA_SSID, WiFi.localIP().toString().c_str(), HUB_HOSTNAME);
    udp.stop();
    udpOpen = false;
    startServices();
  } else if (!up && wifiUp) {
    hubLog("lost \"%s\", joining again", HUB_STA_SSID);
  }
  wifiUp = up;
#else
  if (!started && millis() >= HUB_AP_START_DELAY_MS) {
    started = true;
    startHotspot();
    startServices();
  }
#endif
}

