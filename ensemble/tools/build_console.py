#!/usr/bin/env python3
"""Pack the console into one file, for the places that need it that way.

The console is three files in ensemble/console/ (index.html, app.js and the
generated pfe_sim.wasm.js) and opens straight from disk. Two readers want a
single file instead:

  the hub      serves the page from its own flash at http://192.168.66.1/ :
               ensemble/hub/src/console_page.h, the page gzipped as a C array.
               Committed, so building the hub needs no Python step.
  a person     who wants one .html to pass on:  --single out.html

Usage:
  python ensemble/tools/build_console.py            write hub/src/console_page.h
  python ensemble/tools/build_console.py --check    fail if it is out of date
  python ensemble/tools/build_console.py --single ensemble-console.html
"""
import gzip
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONSOLE = ROOT / "console"
HEADER = ROOT / "hub" / "src" / "console_page.h"

SCRIPT = re.compile(r'<script src="([^"]+)"></script>')


def single_page(hub: bool) -> str:
    html = (CONSOLE / "index.html").read_text(encoding="utf-8")

    def inline(match):
        code = (CONSOLE / match.group(1)).read_text(encoding="utf-8")
        # A literal </script> inside a script would end it early.
        return "<script>\n" + code.replace("</script", "<\\/script") + "</script>"

    html, count = SCRIPT.subn(inline, html)
    if count != 2:
        raise SystemExit(f"expected two <script src> tags in index.html, found {count}")
    if hub:
        # The page looks for this to know the hub itself is serving it, and
        # then opens the hub's WebSocket instead of starting the demo.
        html = html.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<meta name="pfe-hub" content="1">', 1)
    return html


def header_text() -> str:
    data = gzip.compress(single_page(hub=True).encode("utf-8"), compresslevel=9, mtime=0)
    lines = [
        "// Generated by ensemble/tools/build_console.py from ensemble/console/ - do not edit.",
        "// The console page, gzipped, as the hub serves it at /.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"static const size_t CONSOLE_PAGE_GZ_LEN = {len(data)};",
        "static const uint8_t CONSOLE_PAGE_GZ[] = {",
    ]
    for i in range(0, len(data), 20):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    args = sys.argv[1:]
    if args[:1] == ["--single"] and len(args) == 2:
        out = Path(args[1])
        out.write_text(single_page(hub=False), encoding="utf-8", newline="\n")
        print(f"{out}: {out.stat().st_size} bytes")
        return 0
    text = header_text()
    if args == ["--check"]:
        if not HEADER.exists() or HEADER.read_text(encoding="utf-8") != text:
            print("hub/src/console_page.h is out of date: run python ensemble/tools/build_console.py", file=sys.stderr)
            return 1
        print("hub/src/console_page.h is up to date")
        return 0
    if args:
        print(__doc__, file=sys.stderr)
        return 2
    HEADER.write_text(text, encoding="utf-8", newline="\n")
    size = re.search(r"CONSOLE_PAGE_GZ_LEN = (\d+)", text).group(1)
    print(f"{HEADER.relative_to(ROOT.parent)}: the page is {size} bytes gzipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
