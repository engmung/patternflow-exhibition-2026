#!/usr/bin/env python3
"""Build the console's demo simulator: core/pfe_wasm.cpp -> console/pfe_sim.wasm.js.

The output is the WebAssembly module as base64 inside a script, so the
console loads it with a plain <script src> - which works when index.html is
opened straight from disk, where fetch() of a .wasm does not. It is
committed, so this is only needed after changing ensemble/core/.
It needs one of:

  - clang with the wasm32 target and wasm-ld (Linux: the clang and lld packages), or
  - zig:  python -m pip install ziglang   (the same compiler the host tests can use)

Usage:  python ensemble/tools/build_wasm.py
"""
import base64
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "core" / "pfe_wasm.cpp"
OUT = ROOT / "console" / "pfe_sim.wasm.js"

COMMON = [
    "-std=c++17", "-Os", "-nostdlib", "-fno-exceptions", "-fno-rtti", "-fno-builtin",
    "-fno-threadsafe-statics", "-fvisibility=hidden", "-Wall", "-Wextra",
    "-Wl,--no-entry", "-Wl,--strip-all", "-Wl,-z,stack-size=262144",
]


def candidates():
    clang = shutil.which("clang++")
    if clang and shutil.which("wasm-ld"):
        yield "clang", [clang, "--target=wasm32", *COMMON]
    try:
        import ziglang  # noqa: F401
        yield "zig", [sys.executable, "-m", "ziglang", "c++", "-target", "wasm32-freestanding", *COMMON]
    except ImportError:
        pass
    zig = shutil.which("zig")
    if zig:
        yield "zig", [zig, "c++", "-target", "wasm32-freestanding", *COMMON]


def main():
    want = sys.argv[1] if len(sys.argv) > 1 else None
    tried = []
    for name, cmd in candidates():
        if want and name != want:
            continue
        tried.append(name)
        with tempfile.TemporaryDirectory() as tmp:
            wasm = Path(tmp) / "pfe_sim.wasm"
            result = subprocess.run([*cmd, "-o", str(wasm), str(SRC)], capture_output=True, text=True)
            if result.returncode == 0 and wasm.exists():
                if result.stderr.strip():
                    print(result.stderr.strip())
                data = wasm.read_bytes()
                OUT.write_text(
                    "// Generated by ensemble/tools/build_wasm.py from ensemble/core/ - do not edit.\n"
                    f"window.PFE_SIM_WASM = \"{base64.b64encode(data).decode('ascii')}\";\n",
                    encoding="ascii", newline="\n")
                print(f"{OUT.relative_to(ROOT.parent)}: {len(data)} bytes of wasm ({name})")
                return 0
        print(f"{name} failed:\n{result.stderr.strip()}", file=sys.stderr)
    if not tried:
        print("No compiler found. Install clang + lld, or: python -m pip install ziglang", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
